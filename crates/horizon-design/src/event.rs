/// The pointer image a widget wants to display when hovered.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub enum Cursor {
    /// The default pointer image, typically an arrow.
    #[default]
    Default,
    /// A hand indicating a clickable item, typically a link.
    Pointer,
    /// A text selection pointer, typically an I-beam.
    Text,
    /// An open hand for something that can be dragged.
    Grab,
    /// A closed hand for something that is being dragged.
    Grabbing,
}

/// A mouse or touchpad button.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum PointerButton {
    /// Usually the the left button.
    Primary,
    /// Usually the right button.
    Secondary,
    /// The middle button, often a scroll wheel.
    Middle,
}

/// The modifier keys currently pressed during an event.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct Modifiers {
    pub caps: bool,
    pub shift: bool,
    pub ctrl: bool,
    pub alt: bool,
    pub meta: bool,
}

/// A key by what it means after the keymap has been applied.
///
/// Only the keys that widgets handle are listed here. All other
/// keys are represented by `Key::Char` or `Key::Other`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Key {
    Escape,
    Tab,
    Enter,
    Space,
    Backspace,
    Delete,
    Left,
    Right,
    Up,
    Down,
    Home,
    End,
    PageUp,
    PageDown,
    Char(char),
    F(u8),
    Other,
}

/// A keyboard press event. Releases aren't delivered.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct KeyEvent {
    /// The key that was pressed.
    pub key: Key,
    /// The text that was generated by the key press.
    pub text: Option<String>,
    /// The modifier keys that were pressed during the event.
    pub mods: Modifiers,
    /// Whether this event is a repeat from holding down the key.
    pub repeat: bool,
}

impl KeyEvent {
    pub fn new(key: Key) -> Self {
        Self {
            key,
            text: None,
            mods: Modifiers::default(),
            repeat: false,
        }
    }

    /// Sets the modifier keys for the key event.
    pub fn with_mods(mut self, mods: Modifiers) -> Self {
        self.mods = mods;
        self
    }

    /// Creates a `KeyEvent` for a character key press.
    pub fn char(c: char) -> Self {
        Self {
            key: Key::Char(c),
            text: Some(c.to_string()),
            mods: Modifiers::default(),
            repeat: false,
        }
    }
}

#[derive(Debug, Clone, PartialEq)]
pub enum Event {
    Key(KeyEvent),
}
